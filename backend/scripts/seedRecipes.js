async function seed() {
  try {
    const mongoUri = process.env.MONGO_URI || 'mongodb://localhost:27017/neurofit';
    await mongoose.connect(mongoUri);
    console.log('🌱 Connected to MongoDB Atlas for Indian & USDA Recipes Seeding...');

    console.log('🧹 Clearing existing recipes...');
    await Recipe.deleteMany({});

    const usdaList = Object.entries(usdaHealthyRecipes).map(([key, r], idx) => ({
      id: `rec_usda_${key}`,
      ...r,
      sortOrder: 50 + idx,
    }));

    const allToSeed = [...indianRecipes, ...usdaList];
    console.log(`🚀 Inserting ${allToSeed.length} verified Indian and USDA recipes...`);
    const result = await Recipe.insertMany(allToSeed);

    console.log(`✅ Successfully seeded ${result.length} recipes (Indian + USDA) into MongoDB Atlas!`);
    process.exit(0);
  } catch (err) {
    console.error('❌ Error seeding recipes:', err);
    process.exit(1);
  }
}

seed();
