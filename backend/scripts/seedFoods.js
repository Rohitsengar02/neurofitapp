async function seed() {
  try {
    const mongoUri = process.env.MONGO_URI || 'mongodb://localhost:27017/neurofit';
    await mongoose.connect(mongoUri);
    console.log('🌱 Connected to MongoDB Atlas for Foods Seeding...');

    console.log('🧹 Clearing existing food items...');
    await FoodItem.deleteMany({});

    console.log(`🚀 Inserting ${foods.length} verified fitness food items...`);
    const result = await FoodItem.insertMany(foods);

    console.log(`✅ Successfully seeded ${result.length} food items into MongoDB Atlas!`);
    process.exit(0);
  } catch (err) {
    console.error('❌ Error seeding food items:', err);
    process.exit(1);
  }
}

seed();
